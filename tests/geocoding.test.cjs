const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../js/geocoding.js'), 'utf8');
const context = vm.createContext({URL, URLSearchParams});
vm.runInContext(source.slice(0, source.indexOf('(function ()')), context);
const config = {apiKey:'test', contexto:'Nueva Imperial, Chile', pais:'cl', maxResultados:5};
const bounds = [-73,-38.8,-72.9,-38.7];
const url = context.buildGeocodingUrl('Pedro Lagos 0145',config,bounds);
assert.equal(url.searchParams.get('text'),'Pedro Lagos 0145, Nueva Imperial, Chile');
assert.equal(url.searchParams.get('filter'),'rect:-73,-38.8,-72.9,-38.7|countrycode:cl');
assert.equal(context.buildGeocodingUrl('Prat 65, Nueva Imperial, Chile',config,bounds).searchParams.get('text'),'Prat 65, Nueva Imperial, Chile');
assert.equal(context.isGeocodingResultInBounds({lon:-72.95,lat:-38.74,country_code:'cl'},bounds,'cl'),true);
assert.equal(context.isGeocodingResultInBounds({lon:-70,lat:-33,country_code:'cl'},bounds,'cl'),false);
assert.equal(context.isGeocodingResultInBounds({lon:null,lat:-38.74,country_code:'cl'},bounds,'cl'),false);
assert.match(context.geocodingResultDetail({result_type:'street'}),/aproximada/);
assert.match(context.geocodingResultDetail({result_type:'building',housenumber:'0145',rank:{confidence:0.95}}),/numeración/);
console.log('Geocoding: ceros iniciales, contexto, filtro territorial y precisión OK.');
